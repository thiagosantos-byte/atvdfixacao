create table if not exists public.votes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  candidate_id bigint not null references public.candidates(id) on delete restrict,
  created_at timestamptz not null default now()
);
alter table public.votes enable row level security;
revoke all on public.votes from anon, authenticated;

create or replace function public.get_vote_results()
returns table (candidate_id bigint, candidate_name text, vote_count bigint)
language sql stable security definer set search_path = public
as $$
  select c.id, c.name, count(v.id)::bigint
  from public.candidates c
  left join public.votes v on v.candidate_id = c.id
  group by c.id, c.name
  order by c.id;
$$;
revoke all on function public.get_vote_results() from public;
grant execute on function public.get_vote_results() to anon, authenticated;

create or replace function public.has_voted()
returns boolean
language sql stable security definer set search_path = public, auth
as $$
  select auth.uid() is not null and exists (select 1 from public.votes where user_id = auth.uid());
$$;
revoke all on function public.has_voted() from public, anon;
grant execute on function public.has_voted() to authenticated;

create or replace function public.cast_vote(p_candidate_id bigint)
returns table (candidate_id bigint, candidate_name text, vote_count bigint)
language plpgsql security definer set search_path = public, auth
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'Faça login antes de votar.' using errcode = '42501';
  end if;
  if not exists (select 1 from public.candidates where id = p_candidate_id) then
    raise exception 'Candidato inválido.' using errcode = '22023';
  end if;
  insert into public.votes (user_id, candidate_id) values (v_user_id, p_candidate_id);
  return query select * from public.get_vote_results();
exception when unique_violation then
  raise exception 'Esta conta já registrou um voto.' using errcode = '23505';
end;
$$;
revoke all on function public.cast_vote(bigint) from public, anon;
grant execute on function public.cast_vote(bigint) to authenticated;


