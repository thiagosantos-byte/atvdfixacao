create table if not exists public.candidate_vote_totals (
  candidate_id bigint primary key references public.candidates(id) on delete cascade,
  vote_count bigint not null default 0 check (vote_count >= 0)
);
alter table public.candidate_vote_totals enable row level security;
drop policy if exists "FrontLab vote totals are public to read" on public.candidate_vote_totals;
create policy "FrontLab vote totals are public to read" on public.candidate_vote_totals for select to anon, authenticated using (true);
grant select on public.candidate_vote_totals to anon, authenticated;
revoke insert, update, delete, truncate, references, trigger on public.candidate_vote_totals from anon, authenticated;

insert into public.candidate_vote_totals(candidate_id,vote_count)
select c.id,count(v.id)::bigint from public.candidates c left join public.votes v on v.candidate_id=c.id group by c.id
on conflict(candidate_id) do update set vote_count=excluded.vote_count;

create or replace function private.increment_candidate_vote_total()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  insert into public.candidate_vote_totals(candidate_id,vote_count) values(new.candidate_id,1)
  on conflict(candidate_id) do update set vote_count=public.candidate_vote_totals.vote_count+1;
  return new;
end;
$$;
revoke all on function private.increment_candidate_vote_total() from public, anon, authenticated;
drop trigger if exists votes_increment_candidate_total on public.votes;
create trigger votes_increment_candidate_total after insert on public.votes for each row execute function private.increment_candidate_vote_total();

create or replace function public.get_vote_results()
returns table(candidate_id bigint,candidate_name text,vote_count bigint)
language sql stable set search_path=''
as $$
  select c.id,c.name,coalesce(t.vote_count,0)::bigint
  from public.candidates c left join public.candidate_vote_totals t on t.candidate_id=c.id
  order by c.id;
$$;
revoke all on function public.get_vote_results() from public, anon, authenticated;
grant execute on function public.get_vote_results() to anon, authenticated;
